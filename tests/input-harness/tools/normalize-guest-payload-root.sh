#!/usr/bin/env bash
# Remove bootstrap state whose bytes depend on the producer host or wall clock.
set -euo pipefail

root=${1-}
if [[ -z "$root" || ! -d "$root/etc" || ! -d "$root/var" ]]; then
    echo 'guest payload normalize: reason=invalid_payload_root' >&2
    exit 64
fi
root=$(realpath -e "$root")
if [[ "$root" == / ]]; then
    echo 'guest payload normalize: reason=invalid_payload_root' >&2
    exit 64
fi
epoch=${SOURCE_DATE_EPOCH-}
if [[ ! "$epoch" =~ ^[1-9][0-9]{0,17}$ ]]; then
    echo 'guest payload normalize: reason=invalid_source_date_epoch' >&2
    exit 64
fi
epoch_days=$((epoch / 86400))
if ((epoch_days == 0)); then
    echo 'guest payload normalize: reason=invalid_source_date_epoch' >&2
    exit 64
fi

# Host identity and network resolver files are copied or generated by
# bootstrap tools and are not needed by the offline harness sysroot.
replace_file() {
    path=$1
    content=$2
    if [[ -e "$path" || -L "$path" ]]; then
        find "$path" -maxdepth 0 -delete
    fi
    printf '%s' "$content" > "$path"
}
replace_file "$root/etc/hostname" $'pf-input-harness\n'
replace_file "$root/etc/hosts" $'127.0.0.1 localhost\n'
replace_file "$root/etc/resolv.conf" $'# offline test payload\n'
replace_file "$root/etc/machine-id" ''
chmod 0444 "$root/etc/machine-id"
if [[ -e "$root/var/lib/dbus/machine-id" && ! -L "$root/var/lib/dbus/machine-id" ]]; then
    : > "$root/var/lib/dbus/machine-id"
fi

# account-management postinst scripts stamp password-aging state with their
# execution date. A zero date means "change at next login", so use the fixed,
# nonzero snapshot day for every account instead.
if [[ -f "$root/etc/shadow" && ! -L "$root/etc/shadow" ]]; then
    PF_SHADOW_EPOCH_DAYS=$epoch_days python3 -B - "$root/etc/shadow" <<'PY'
import os
import pathlib
import sys
import tempfile

path = pathlib.Path(sys.argv[1])
stat = path.stat()
lines = []
for line in path.read_text(encoding="utf-8").splitlines():
    fields = line.split(":")
    if len(fields) >= 3:
        fields[2] = os.environ["PF_SHADOW_EPOCH_DAYS"]
    lines.append(":".join(fields))
fd, temporary = tempfile.mkstemp(prefix=".shadow.", dir=path.parent)
try:
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as output:
        output.write("\n".join(lines) + ("\n" if lines else ""))
        output.flush()
        os.fchmod(output.fileno(), stat.st_mode)
        os.fchown(output.fileno(), stat.st_uid, stat.st_gid)
    os.replace(temporary, path)
except BaseException:
    try:
        os.unlink(temporary)
    except FileNotFoundError:
        pass
    raise
PY
fi

# These files contain install times, host entropy, generated cache keys, or
# bytecode headers. They are runtime caches/evidence, not package inputs.
for path in \
    "$root/var/log" \
    "$root/var/lib/apt/lists" \
    "$root/var/cache/apt/archives" \
    "$root/var/cache/fontconfig" \
    "$root/tmp" \
    "$root/var/tmp"; do
    if [[ -d "$path" ]]; then
        find "$path" -mindepth 1 -delete
    fi
done
find "$root" -type f -name '*.pyc' -delete
find "$root" -depth -type d -name __pycache__ -empty -delete
if [[ -d "$root/etc/ssh" ]]; then
    find "$root/etc/ssh" -type f -name 'ssh_host_*_key*' -delete
fi
for path in \
    "$root/etc/shadow-" \
    "$root/etc/passwd-" \
    "$root/etc/group-" \
    "$root/etc/gshadow-" \
    "$root/var/lib/dpkg/status-old" \
    "$root/var/lib/dpkg/diversions-old" \
    "$root/var/lib/dpkg/available-old" \
    "$root/var/cache/debconf/config.dat-old" \
    "$root/var/cache/debconf/templates.dat-old" \
    "$root/var/cache/debconf/passwords.dat-old" \
    "$root/var/lib/systemd/catalog/database" \
    "$root/etc/ld.so.cache" \
    "$root/var/cache/ldconfig/aux-cache" \
    "$root/var/lib/systemd/random-seed"; do
    if [[ -e "$path" || -L "$path" ]]; then
        find "$path" -maxdepth 0 -delete
    fi
done
if [[ -d "$root/usr/share/icons" ]]; then
    find "$root/usr/share/icons" -type f -name icon-theme.cache -delete
fi
