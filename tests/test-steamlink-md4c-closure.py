#!/usr/bin/env python3
"""Steam Link shell NEEDED closure must be mechanical, seeded and bound to the pinned build.

r5 on image d4b59851 failed at launch with
'steamlink/bin/shell: error while loading shared libraries: libmd4c.so.0'
(ExecMainStatus=127). The closure must come from readelf over the pinned
archive, not a hand list: build/steamlink-shell-needed-closure.json is
generated by scripts/steamlink-needed-closure.py and bound to the archive sha.
"""
import json
from pathlib import Path
import unittest

ROOT = Path(__file__).resolve().parents[1]
SEEDS = ROOT / "build/app-platform-runtime-a133-open-v1.json"
MANIFEST = ROOT / "build/steamlink-shell-needed-closure.json"
TOOL = ROOT / "scripts/steamlink-needed-closure.py"
PINNED_ARCHIVE_SHA256 = "980f19f22069902e9c3cc5002d90adeee76ab514d35fde4377534a70783dc531"
PINNED_VERSION = "1.4.5.327"


class Md4cClosureTest(unittest.TestCase):
    def seeds(self):
        return {Path(s).name for s in json.loads(SEEDS.read_text())["seeds"]}

    def test_libmd4c_is_a_platform_runtime_seed(self):
        self.assertIn("libmd4c.so.0", self.seeds())

    def test_closure_tool_and_manifest_exist(self):
        self.assertTrue(TOOL.is_file(), "missing mechanical closure tool")
        self.assertTrue(MANIFEST.is_file(), "missing generated closure manifest")

    def test_manifest_bound_to_pinned_build(self):
        m = json.loads(MANIFEST.read_text())
        self.assertEqual(m["archive_sha256"], PINNED_ARCHIVE_SHA256)
        self.assertEqual(m["version"], PINNED_VERSION)

    def test_every_unresolved_soname_is_seeded_or_bound(self):
        m = json.loads(MANIFEST.read_text())
        provided = self.seeds() | set(m.get("runtime_binds", []))
        missing = [s for s in m["unresolved"] if s not in provided]
        self.assertEqual(missing, [])
        self.assertIn("libmd4c.so.0", m["unresolved"])


if __name__ == "__main__":
    unittest.main()
